import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const directory = new URL('./', import.meta.url)
const modulePath = new URL('../../apps/desktop/build/windows-registration.ps1', directory)
const wrapperPath = new URL('./repair.ps1', directory)
const importLine = ". (Join-Path $PSScriptRoot '../../apps/desktop/build/windows-registration.ps1')"

/**
 * Build a single-file launcher whose embedded PowerShell needs no adjacent files.
 * @param moduleSource Shared registration inspection and repair implementation.
 * @param wrapperSource User confirmation and reporting entry point.
 * @param scope Explicit registry scope compiled into this launcher.
 * @returns ASCII CMD text with a UTF-8 payload and Windows line endings.
 */
export function buildLauncher(moduleSource, wrapperSource, scope) {
  if (!['CurrentUser', 'AllUsers'].includes(scope)) throw new Error('Unknown repair scope')
  if (wrapperSource.split(importLine).length !== 2) throw new Error('Repair module import must appear exactly once')
  const payload = wrapperSource.replace(importLine, () => moduleSource.replace(/^\uFEFF/, ''))
  const encoded = Buffer.from(payload.replace(/^\uFEFF/, ''), 'utf8').toString('base64').match(/.{1,76}/g).join('\r\n')
  const command = "$payload = ([IO.File]::ReadAllText($env:ODSH_REPAIR_LAUNCHER) -split ':ODSH_PAYLOAD\\r?\\n', 2)[1].Trim(); & ([ScriptBlock]::Create([Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($payload)))) -Scope " + scope
  return [
    '@echo off',
    'setlocal DisableDelayedExpansion',
    'rem Generated by generate-launchers.mjs. Contains the complete audited PowerShell payload.',
    'set "ODSH_REPAIR_LAUNCHER=%~f0"',
    'set "ODSH_REPAIR_POWERSHELL=%SystemRoot%\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"',
    'if exist "%SystemRoot%\\Sysnative\\WindowsPowerShell\\v1.0\\powershell.exe" set "ODSH_REPAIR_POWERSHELL=%SystemRoot%\\Sysnative\\WindowsPowerShell\\v1.0\\powershell.exe"',
    'if not exist "%ODSH_REPAIR_POWERSHELL%" (',
    '  echo Windows PowerShell was not found. Nothing was changed.',
    '  pause',
    '  exit /b 1',
    ')',
    `"%ODSH_REPAIR_POWERSHELL%" -NoLogo -NoProfile -STA -ExecutionPolicy Bypass -Command "${command}"`,
    'set "ODSH_REPAIR_RESULT=%ERRORLEVEL%"',
    'echo.',
    'echo Repair exit code: %ODSH_REPAIR_RESULT%',
    'echo Keep this window open if it reports an error.',
    'pause',
    'exit /b %ODSH_REPAIR_RESULT%',
    ':ODSH_PAYLOAD',
    encoded,
    '',
  ].join('\r\n')
}

/**
 * Generate launchers, or fail when checked-in launchers differ from their sources.
 * @param checkOnly Verify freshness without writing files when true; generate otherwise.
 */
export function generateLaunchers(checkOnly = false) {
  const moduleSource = readFileSync(modulePath, 'utf8')
  const wrapperSource = readFileSync(wrapperPath, 'utf8')
  for (const [filename, scope] of [['START-REPAIR.cmd', 'CurrentUser'], ['START-ALL-USERS-REPAIR.cmd', 'AllUsers']]) {
    const target = new URL(filename, directory)
    const content = buildLauncher(moduleSource, wrapperSource, scope)
    if (checkOnly) {
      if (readFileSync(target, 'utf8') !== content) throw new Error(`Stale repair launcher: ${filename}`)
    } else {
      writeFileSync(target, content, 'ascii')
    }
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) generateLaunchers(process.argv.includes('--check'))
